"""Export the detection figures of the paper (the section after localization) as pgfplots .tex files.

    uv run python scripts/exporters/export_detection_tex.py --out-dir <paper repo>/plots/03_detection

Reads the manifest keys ``yesno_dropout`` / ``yesno_noise`` (the question "was a perturbation applied?") and
``yesno_ctrl_dropout`` / ``yesno_ctrl_noise`` (the control questions, whose answer is NO, YES or undetermined) of the
eight models of Table 1 in ``notebooks/paper/sweeps.yaml`` through the local cache (``notebooks/wandb_cache.py``),
and the same keys of the OLMo training stages (``olmo_stages``: ``yesno_stage_<stage>_*``, ``yesno_ctrl_stage_<stage>_*``;
RLVR is ``olmo3_32b``), which run at the strengths of the RLVR range.
Every plotted quantity is ``accuracy_primary`` of runs whose YES class is the applied perturbation, that is, the
frequency of YES. The x axis is the position of the strength in the model's range of Table 1 (0 = min, 100 = max);
the run without perturbation is drawn at x = -25 ("none").

Outputs:
    00_detection_main.tex       frequency of YES to "was a perturbation applied?", dropout (left) and noise (right)
    01_detection_controls.tex   frequency of YES to the control questions, dropout (top) and noise (bottom)
    02_detection_olmo_stages.tex  OLMo stages: detection question (left) and undetermined questions (right)
    olmo_stage_ranges.tex       (--appendix-dir) localization and comprehension curves of the OLMo stages, whose
                                bounds (scripts/bounds.py) set the strengths of each stage
"""

