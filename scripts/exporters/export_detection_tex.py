def ranges_figure() -> str:
    """Localization and comprehension curves of the four stages, as bounds.py reads them (constrained accuracy)."""
    metric = "accuracy_constrained_primary"
    columns = [  # sweep prefix, metric, SE column, title, ymin
        ("loc", metric, "accuracy_se_constrained_primary", "Localization", 0.0),
        (
            "ctrl",
            f"content_{metric}",
            f"content_{metric.replace('accuracy', 'accuracy_se')}",
            "Comprehension controls",
            50.0,
        ),
    ]
    xmax = {"dropout": 0.98, "noise": 0.5}
    xlabel = {"dropout": "Dropout rate $p$", "noise": "Noise SD $\\sigma$"}
    groups = ""
    for pert in ("dropout", "noise"):
        for prefix, col, se_col, title, ymin in columns:
            opts = [
                f"xlabel={{\\small {xlabel[pert]}}}",
                f"xmin=0, xmax={xmax[pert]}",
                f"ymin={ymin}, ymax=100.0",
            ]
            if pert == "dropout":
                opts.append(f"title={{\\small {title}}}")
            opts.append("ylabel={\\small Accuracy (\\%)}")
            groups += f"\\nextgroupplot[{', '.join(opts)}]\n"
            for _, model, *_, color in STAGES:
                df = bounds.load_family(_MANIFEST[model], f"{prefix}_{pert}", PROJECT)
                df = df[df[RATE_COL[pert]] <= xmax[pert]]
                g = df.groupby(RATE_COL[pert])
                xs = [round(float(x), 4) for x in g[col].mean().index]
                ys = list(100 * g[col].mean())
                se = list(
                    100 * g[se_col].apply(lambda v: (v.pow(2).sum()) ** 0.5 / len(v))
                )
                lo, hi = (
                    [y - d for y, d in zip(ys, se, strict=True)],
                    [y + d for y, d in zip(ys, se, strict=True)],
                )
                groups += (
                    f"\\addplot[{color}, fill={color}, fill opacity=0.3, draw=none, forget plot] coordinates {{{_band(xs, lo, hi)}}} --cycle;\n"
                    f"\\addplot[{color}, mark=*, mark size=1, line width=1pt, forget plot] coordinates {{{_coords(xs, ys)}}};\n"
                )
            if prefix == "loc":
                groups += f"\\addplot[gray, dashed, line width=0.5pt, forget plot] coordinates {{(0,50) ({xmax[pert]},50)}};\n"
    swatch = "\\tikz\\draw[{}, thick, mark=*, mark size=1.5] plot coordinates {{(0,0) (0.4,0)}}; {{\\small {}}}"
    legend = (
        "\\hspace{1em}\n".join(
            swatch.format(color, label) for label, *_, color in STAGES
        )
        + "\n\\\\[3pt]\n"
    )
    return (
        HEADER
        + "\\begin{figure}[ht]\n\\centering\n"
        + legend
        + "\\tikzsetnextfilename{detection-olmo-stage-ranges}\n"
        "\\begin{tikzpicture}\n"
        "\\begin{groupplot}[\n"
        "    group style={group size=2 by 2, horizontal sep=1.6cm, vertical sep=1.4cm},\n"
        "    height=3.2cm,\n"
        "    width=6.0cm,\n"
        "    scale only axis,\n"
        "    grid=major,\n"
        "    tick label style={font=\\footnotesize},\n"
        "]\n" + groups + "\\end{groupplot}\n\\end{tikzpicture}\n"
        f"\\vspace{{-8pt}}\n\\caption{{{CAPTION_RANGES}}}\n\\label{{fig:appendix_olmo_stage_ranges}}\n\\end{{figure}}\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--out-dir",
        type=Path,
        required=True,
        help="e.g. <paper repo>/plots/03_detection",
    )
    ap.add_argument(
        "--appendix-dir",
        type=Path,
        help="e.g. <paper repo>/plots/11_appendix/detection (writes olmo_stage_ranges.tex)",
    )
    args = ap.parse_args()
    if args.appendix_dir is not None:
        args.appendix_dir.mkdir(parents=True, exist_ok=True)
        (args.appendix_dir / "olmo_stage_ranges.tex").write_text(ranges_figure())
        print(f"wrote {args.appendix_dir / 'olmo_stage_ranges.tex'}")
    args.out_dir.mkdir(parents=True, exist_ok=True)
    runs = {(m, p): _runs(m, p) for m, _, _ in MODELS for p in ("dropout", "noise")}
    for name, render in (
        ("00_detection_main.tex", main_figure),
        ("01_detection_controls.tex", controls_figure),
        ("02_detection_olmo_stages.tex", stages_figure),
    ):
        (args.out_dir / name).write_text(render(runs))
        print(f"wrote {args.out_dir / name}")


if __name__ == "__main__":
    main()
