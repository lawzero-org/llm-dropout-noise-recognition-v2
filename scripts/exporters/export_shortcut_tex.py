"""Export the log-probability analysis of the appendix (localization, second controls) as pgfplots .tex files.

    uv run python scripts/exporters/export_shortcut_tex.py --out-dir <paper repo>/plots/11_appendix/logprob

Reads the ``per_sample_logprobs`` tables of the 32 runs of ``scripts/shortcut_analysis.py`` (listed by
``scripts/logprob_runs.py``; 8 models x {dropout, noise} x {low, high} strength, found on W&B by
``experiment.stage = logprob_low / logprob_high``). Tables are downloaded once into ``notebooks/artifacts``.

Each figure is a groupplot with two models per row, one figure per perturbation:
    shortcut_rates_<pert>.tex                       comparison rates P(B)<P(A), P(A*)<P(B), P(B*)<P(A)
    shortcut_eff_pertA_on_A_<pert>.tex              logP(A*) - logP(A)
    shortcut_eff_pertB_on_B_<pert>.tex              logP(B*|A) - logP(B|A)
    shortcut_eff_pertA_on_B_<pert>.tex              logP(B|A*) - logP(B|A)
    shortcut_eff_pertB_minus_pertA_on_B_<pert>.tex  logP(B*|A) - logP(B|A*)
"""

import argparse
import glob
import json
import os
from pathlib import Path

import numpy as np
import pandas as pd

# W&B project; the entity is WANDB_ENTITY or your default entity.
PROJECT = os.environ.get("WANDB_PROJECT", "llm-dropout-noise")
ART_DIR = Path(__file__).resolve().parents[2] / "notebooks" / "artifacts"
HEADER = (
    "% Auto-generated by scripts/exporters/export_shortcut_tex.py -- do not edit by hand.\n"
    "% Uses plain xcolor mixes; model names \\model{<key>} from the preamble.\n"
)
REGIME_COLOR = {"high": "blue!60!black", "low": "orange!80!black"}
REFLINE_COLOR = "gray"
MODELS = [
    "gemma4_31b",
    "llama3_8b",
    "mistral_small_24b",
    "olmo3_32b",
    "qwen3_14b",
    "qwen3_32b",
    "qwen3_8_27b",
    "seed_oss_36b",
]
MODEL_TEX = {
    "gemma4_31b": r"\model{gemma31}",
    "llama3_8b": r"\model{llama8}",
    "mistral_small_24b": r"\model{mistral24}",
    "olmo3_32b": r"\model{olmo32}",
    "qwen3_14b": r"\model{qwen14}",
    "qwen3_32b": r"\model{qwen32}",
    "qwen3_8_27b": r"\model{qwen27}",
    "seed_oss_36b": r"\model{seed36}",
}
PERTURBATIONS = ["DROPOUT", "NOISE"]
PERT_TEX = {"DROPOUT": "Dropout", "NOISE": "Noise"}
REGIMES = ["high", "low"]

EFFECTS = [
    "eff_pertA_on_A",
    "eff_pertB_on_B",
    "eff_pertA_on_B",
    "eff_pertB_minus_pertA_on_B",
]

# Delta expression printed above each histogram figure (a label, not prose).
EFFECT_TITLE = {
    "eff_pertA_on_A": r"$\Delta = \log P(A^{\ast}) - \log P(A)$",
    "eff_pertB_on_B": r"$\Delta = \log P(B^{\ast}\mid A) - \log P(B\mid A)$",
    "eff_pertA_on_B": r"$\Delta = \log P(B\mid A^{\ast}) - \log P(B\mid A)$",
    "eff_pertB_minus_pertA_on_B": r"$\Delta = \log P(B^{\ast}\mid A) - \log P(B\mid A^{\ast})$",
}

# Short x-axis labels for the three comparison rates.
RATE_KEYS = ["clean_B_lt_A", "pertA_A_lt_B", "pertB_B_lt_A"]
RATE_LABELS = [r"$P(B) < P(A)$", r"$P(A^{\ast}) < P(B)$", r"$P(B^{\ast}) < P(A)$"]

NUM_BINS = 50


def discover_runs() -> dict:
    """(model, perturbation, regime) -> run id of the finished ``experiment.stage=logprob_<regime>`` runs."""
    import wandb
    import yaml

    conf = Path(__file__).resolve().parents[2] / "src" / "spe" / "conf" / "model"
    short = {yaml.safe_load(open(conf / f"{m}.yaml"))["name"]: m for m in MODELS}
    runs = wandb.Api(timeout=60).runs(
        PROJECT,
        filters={
            "config.experiment.stage": {"$in": ["logprob_low", "logprob_high"]},
            "state": "finished",
        },
    )
    ids: dict = {}
    for r in runs:
        key = (
            short[r.config["model"]["name"]],
            r.config["perturbation"]["target_perturbation"],
            r.config["experiment"]["stage"].removeprefix("logprob_"),
        )
        if key in ids:
            raise ValueError(f"two finished runs for {key}: {ids[key]}, {r.id}")
        ids[key] = r.id
    missing = [
        (m, p, g)
        for m in MODELS
        for p in PERTURBATIONS
        for g in REGIMES
        if (m, p, g) not in ids
    ]
    if missing:
        raise ValueError(f"no finished run for {missing}")
    return ids


def load_table(run_id: str) -> pd.DataFrame:
    adir = ART_DIR / f"run-{run_id}-per_sample_logprobs:v0"
    if os.environ.get("USE_WANDB") or not adir.exists():
        import wandb

        run = wandb.Api().run(f"{PROJECT}/{run_id}")
        artifact = next(
            a for a in run.logged_artifacts() if "per_sample_logprobs" in a.name
        )
        adir = Path(artifact.download(root=str(adir)))
    files = glob.glob(f"{adir}/**/*.table.json", recursive=True)
    if not files:
        raise FileNotFoundError(f"no .table.json for run {run_id} under {adir}")
    with open(files[0]) as f:
        raw = json.load(f)
    return pd.DataFrame(raw["data"], columns=raw["columns"])


def load_all() -> pd.DataFrame:
    frames = []
    for (model, pert, regime), run_id in discover_runs().items():
        df = load_table(run_id)
        df["model"] = model
        df["perturbation_type"] = pert
        df["regime"] = regime
        frames.append(df)
    df = pd.concat(frames, ignore_index=True)
    df["eff_pertA_on_A"] = df["lp_pertA_A"] - df["lp_clean_A"]
    df["eff_pertA_on_B"] = df["lp_pertA_B"] - df["lp_clean_B"]
    df["eff_pertB_on_A"] = df["lp_pertB_A"] - df["lp_clean_A"]
    df["eff_pertB_on_B"] = df["lp_pertB_B"] - df["lp_clean_B"]
    df["eff_pertB_minus_pertA_on_B"] = df["lp_pertB_B"] - df["lp_pertA_B"]
    return df


def comparison_rates(df: pd.DataFrame) -> dict:
    rates = {}
    grouped = df.groupby(["model", "perturbation_type", "regime"])
    for (model, pert, regime), sub in grouped:
        rates[(model, pert, regime)] = {
            "clean_B_lt_A": float((sub["lp_clean_B"] < sub["lp_clean_A"]).mean()),
            "pertA_A_lt_B": float((sub["lp_pertA_A"] < sub["lp_pertA_B"]).mean()),
            "pertB_B_lt_A": float((sub["lp_pertB_B"] < sub["lp_pertB_A"]).mean()),
        }
    return rates


# ---------------------------------------------------------------------------
# tex helpers
# ---------------------------------------------------------------------------
# the two strengths of scripts/logprob_runs.py: low = bin 0 of Table 1, high = bin 5 (the midpoint of the range)
REGIME_TEX = {
    "DROPOUT": {"high": r"$\tfrac{1}{2}(p_{\min}+p_{\max})$", "low": r"$p_{\min}$"},
    "NOISE": {
        "high": r"$\tfrac{1}{2}(\sigma_{\min}+\sigma_{\max})$",
        "low": r"$\sigma_{\min}$",
    },
}


def legend_line(pert: str) -> str:
    swatch = [
        f"\\tikz\\fill[{REGIME_COLOR[r]}] (0,0) rectangle (0.32,0.16);~{{\\small {REGIME_TEX[pert][r]}}}"
        for r in REGIMES
    ]
    return (
        f"{{\\small\\bfseries {PERT_TEX[pert]}:}}\\hspace{{1em}}"
        + "\\hspace{1.5em}".join(swatch)
    )


# One figure per perturbation; every figure
# is a grid of the models, two per row, filled row-major.
GRID = [MODELS[i : i + 2] for i in range(0, len(MODELS), 2)]


def panel_opts(i: int, j: int, model: str) -> list:
    """Per-panel options for a 2x2 model grid: model name as title, x label
    only on the bottom row."""
    opts = [f"title={{{MODEL_TEX[model]}}}"]
    return opts


# ---------------------------------------------------------------------------
# Fig 1: comparison-rate bars (one slide per perturbation)
# ---------------------------------------------------------------------------
def emit_rates(rates: dict, pert: str) -> str:
    L = [
        r"\centering",
        legend_line(pert) + r"\\[4pt]",
        r"\begin{tikzpicture}",
        r"\begin{groupplot}[",
        f"    group style={{group size=2 by {len(GRID)}, horizontal sep=1.4cm,"
        r" vertical sep=1.1cm, x descriptions at=edge bottom},",
        r"    width=0.52\linewidth, height=3.0cm,",
        r"    every axis/.append style={ybar, bar width=7pt},",
        r"    xmin=0.4, xmax=3.6, ymin=0, ymax=1.18,",
        r"    xtick={1,2,3},",
        f"    xticklabels={{{','.join(RATE_LABELS)}}},",
        r"    ytick={0,0.5,1},",
        r"    tick label style={font=\scriptsize},",
        r"    xticklabel style={font=\fontsize{5}{6}\selectfont},",
        r"    title style={font=\small, yshift=-0.6ex},",
        r"    every axis plot/.append style={draw=none},",
        r"]",
    ]
    # high and low coincide on these binary rates, so label the high bars only.
    label_opts = (
        "nodes near coords, point meta=explicit symbolic, "
        r"every node near coord/.append style={"
        r"font=\fontsize{4.5}{5}\selectfont, anchor=south, inner sep=0.6pt}"
    )
    for i, row in enumerate(GRID):
        for j, model in enumerate(row):
            L.append(f"\\nextgroupplot[{', '.join(panel_opts(i, j, model))}]")
            for regime in REGIMES:
                c = REGIME_COLOR[regime]
                cell = rates[(model, pert, regime)]
                if regime == "high":
                    coords = " ".join(
                        f"({k + 1},{cell[key]:.4f}) [{cell[key]:.2f}]"
                        for k, key in enumerate(RATE_KEYS)
                    )
                    style = f"fill={c}, fill opacity=0.85, {label_opts}"
                else:
                    coords = " ".join(
                        f"({k + 1},{cell[key]:.4f})" for k, key in enumerate(RATE_KEYS)
                    )
                    style = f"fill={c}, fill opacity=0.85"
                L.append(f"\\addplot[{style}] coordinates {{{coords}}};")
            L.append(
                f"\\draw[{REFLINE_COLOR}, dashed, line width=0.4pt] "
                r"(axis cs:0.4,0.5) -- (axis cs:3.6,0.5);"
            )
    L += [r"\end{groupplot}", r"\end{tikzpicture}"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------------------
# Figs 2-5: effect histograms (one slide per perturbation)
# ---------------------------------------------------------------------------
def emit_effect(df: pd.DataFrame, effect: str, pert: str) -> str:
    L = [
        r"\centering",
        legend_line(pert) + r"\\[4pt]",
        r"\begin{tikzpicture}",
        r"\begin{groupplot}[",
        f"    group style={{group size=2 by {len(GRID)}, horizontal sep=1.5cm,"
        r" vertical sep=1.2cm},",
        r"    width=0.52\linewidth, height=3.0cm,",
        r"    tick label style={font=\scriptsize},",
        r"    title style={font=\small, yshift=-0.6ex},",
        r"    every axis plot/.append style={line width=0.2pt},",
        r"    scaled y ticks=false, ytick align=outside,",
        r"    max space between ticks=24,",
        r"]",
    ]
    nrows = len(GRID)
    for i, row in enumerate(GRID):
        for j, model in enumerate(row):
            sub = df[(df["model"] == model) & (df["perturbation_type"] == pert)]
            lo, hi = float(sub[effect].min()), float(sub[effect].max())
            if hi <= lo:
                hi = lo + 1e-6
            edges = np.linspace(lo, hi, NUM_BINS)
            ymax = 1.0
            series = {}
            for regime in REGIMES:
                vals = sub[sub["regime"] == regime][effect].to_numpy()
                counts, _ = np.histogram(vals, bins=edges)
                series[regime] = counts
                ymax = max(ymax, counts.max())
            ymax = ymax * 1.10

            opts = panel_opts(i, j, model)
            opts.append(f"xmin={lo:.4f}, xmax={hi:.4f}")
            opts.append(f"ymin=0, ymax={ymax:.1f}")
            if i == nrows - 1:
                opts.append(r"xlabel={\scriptsize nats}, xlabel style={yshift=0.6ex}")
            L.append(f"\\nextgroupplot[{', '.join(opts)}]")

            for regime in REGIMES:
                c = REGIME_COLOR[regime]
                counts = series[regime]
                # ybar interval: N+1 edges, last height ignored (set 0).
                pts = " ".join(
                    f"({edges[b]:.4f},{int(counts[b])})" for b in range(NUM_BINS - 1)
                )
                pts += f" ({edges[NUM_BINS - 1]:.4f},0)"
                L.append(
                    f"\\addplot[ybar interval, fill={c}, fill opacity=0.5, "
                    f"draw={c}] coordinates {{{pts}}};"
                )
            L.append(
                rf"\draw[{REFLINE_COLOR}, dashed, line width=0.4pt] "
                rf"(axis cs:0,0) -- (axis cs:0,{ymax:.1f});"
            )
    L += [r"\end{groupplot}", r"\end{tikzpicture}"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------------------
def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=Path("plots/11_appendix/logprob"),
        help="output directory (default: plots/11_appendix/logprob, as in the paper repo)",
    )
    args = parser.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)

    df = load_all()
    rates = comparison_rates(df)

    for pert in PERTURBATIONS:
        tag = pert.lower()
        (args.out_dir / f"shortcut_rates_{tag}.tex").write_text(
            HEADER + emit_rates(rates, pert)
        )
        print(f"wrote shortcut_rates_{tag}.tex")
    for effect in EFFECTS:
        for pert in PERTURBATIONS:
            tag = pert.lower()
            (args.out_dir / f"shortcut_{effect}_{tag}.tex").write_text(
                HEADER + emit_effect(df, effect, pert)
            )
            print(f"wrote shortcut_{effect}_{tag}.tex")


if __name__ == "__main__":
    main()
