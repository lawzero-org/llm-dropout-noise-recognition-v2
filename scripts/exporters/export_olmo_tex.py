"""Export the OLMo figures of the paper (Sec. 4.4 and the appendix on pretraining steps) as pgfplots .tex files.

    uv run python scripts/exporters/export_olmo_tex.py --out-dir <paper repo>/plots/11_appendix/olmo

Reads the manifest blocks ``olmo_stages`` and ``olmo_steps`` of ``notebooks/paper/sweeps.yaml`` through the
local cache (``notebooks/wandb_cache.py``); accuracies are exact-token, as in the rest of the paper (the logits of " A"
vs " B" alone would put the step-0 checkpoint, which answers neither, at chance). Strengths are the 11 bins of the
OLMo range of Table 1.

Outputs:
    olmo_stages_wrap.tex             Sec. 4.4: accuracy of every training stage at one strength
    olmo_steps_appendix.tex          pretraining checkpoints at the min / mid / max of the range, (a) dropout (b) noise
    olmo_fig3_content_baseline.tex   pretraining checkpoints at the comprehension question, no perturbation
"""

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "notebooks"))
from wandb_cache import load_sweep  # noqa: E402

_REPO = Path(__file__).resolve().parents[2]
_MANIFEST = yaml.safe_load((_REPO / "notebooks/paper/sweeps.yaml").read_text())
PROJECT = _MANIFEST["project"]
STAGE_SWEEPS = _MANIFEST["olmo_stages"]  # stage_<stage>_<dropout|noise>
STEP_SWEEPS = _MANIFEST[
    "olmo_steps"
]  # step<N>_<loc|ctrl>_<dropout|noise>, step<N>_ctrl_clean
RATE_COL = {"DROPOUT": "perturbation.dropout_rate", "NOISE": "perturbation.noise_std"}
STAGE_BIN = (
    6  # strength of the stage panel (p 0.50 / sigma 0.056: on every stage's plateau)
)
STEP_BINS = [0, 5, 10]  # strengths of the step panels (min / mid / max of the range)
SHADES = [40, 70, 100]  # one shade for each of the STEP_BINS, lightest = weakest
STAGE_ORDER = ["base", "sft", "dpo", "rlvr"]
STAGE_LABELS = {"base": "Base", "sft": "SFT", "dpo": "DPO", "rlvr": "RLVR"}
DROPOUT_COLOR = "green!55!black"
NOISE_COLOR = "orange!80!black"
CONTENT_COLOR = "blue!60!black"
HEADER = (
    "% Auto-generated by scripts/exporters/export_olmo_tex.py -- do not edit by hand.\n"
    "% Data: manifest keys olmo_stages / olmo_steps (project llm-dropout-noise); exact-token accuracy.\n"
    "% Requires \\usepackage{pgfplots}, \\usepgfplotslibrary{groupplots}, \\pgfplotsset{compat=1.18}.\n"
)


def _sweep(sid: str) -> pd.DataFrame:
    return load_sweep(sid, project=PROJECT, require_version=2)


def _binned(df: pd.DataFrame, pert: str) -> pd.DataFrame:
    """Add ``rate`` (strength) and ``bin`` (0..10, rank of the strength in the 11-bin grid)."""
    df = df.copy()
    df["rate"] = df[RATE_COL[pert]].astype(float)
    df["bin"] = df["rate"].rank(method="dense").astype(int) - 1
    return df


def _steps(kind: str, pert: str) -> pd.DataFrame:
    frames = []
    for key, sid in STEP_SWEEPS.items():
        step, k, p = key.split("_")
        if k == kind and p == pert:
            df = _sweep(sid)
            if p in ("dropout", "noise"):
                df = _binned(df, p.upper())
            df["step"] = int(step[4:])
            frames.append(df)
    return pd.concat(frames, ignore_index=True)


def _coords(xs: list, ys: list) -> str:
    return " ".join(f"({a},{b:.2f})" for a, b in zip(xs, ys, strict=True))


def _band(xs: list, lo: list, hi: list) -> str:
    """Closed polygon for a shaded SE band: forward upper + reverse lower."""
    return _coords(xs, hi) + " " + _coords(list(reversed(xs)), list(reversed(lo)))


def _shade(color: str, shade: int) -> str:
    return color if shade == 100 else f"{color}!{shade}"


def stages() -> str:
    rows = {}
    for pert in ("DROPOUT", "NOISE"):
        for stage in STAGE_ORDER:
            df = _binned(_sweep(STAGE_SWEEPS[f"stage_{stage}_{pert.lower()}"]), pert)
            rows[(stage, pert)] = df[df["bin"] == STAGE_BIN].iloc[0]
    rate = {p: float(rows[("base", p)]["rate"]) for p in ("DROPOUT", "NOISE")}

    def errplot(color: str, pert: str) -> str:
        body = " ".join(
            f"({i},{100 * rows[(s, pert)]['accuracy_primary']:.2f}) +- "
            f"(0,{100 * rows[(s, pert)]['accuracy_se_primary']:.2f})"
            for i, s in enumerate(STAGE_ORDER)
        )
        return (
            f"\\addplot[{color}, mark=*, mark size=2, line width=1pt, forget plot, error bars/.cd, y dir=both, "
            f"y explicit, error bar style={{line width=1pt, {color}}}, error mark options={{rotate=90, {color}, "
            f"mark size=3, line width=1pt}}] coordinates {{{body}}};\n"
        )

    return (
        HEADER
        + f"% Panel: training stages at p={rate['DROPOUT']:g}, sigma={rate['NOISE']:g} (bin {STAGE_BIN} of the 11-bin OLMo range).\n"
        + "\\centering\n"
        + f"{{\\scriptsize \\tikz\\draw[{DROPOUT_COLOR}, thick, mark=*, mark size=1.5] plot coordinates {{(0,0) (0.4,0)}}; "
        + f"dropout $p{{=}}{rate['DROPOUT']:g}$\\hspace{{1em}}\\tikz\\draw[{NOISE_COLOR}, thick, mark=*, mark size=1.5] "
        + f"plot coordinates {{(0,0) (0.4,0)}}; noise $\\sigma{{=}}{rate['NOISE']:g}$}}\\\\[2pt]\n"
        + "\\begin{tikzpicture}\n\\begin{axis}[\n    height=3.8cm,\n    width=\\linewidth,\n    grid=major,\n"
        + "    xlabel={\\scriptsize Training stage},\n    ylabel={\\scriptsize Accuracy (\\%)},\n"
        + f"    xtick={{{','.join(str(i) for i in range(len(STAGE_ORDER)))}}},\n"
        + f"    xticklabels={{{','.join(STAGE_LABELS[s] for s in STAGE_ORDER)}}},\n"
        + "    xticklabel style={font=\\scriptsize},\n    yticklabel style={font=\\scriptsize},\n"
        + "    xmin=-0.3, xmax=3.3,\n    ymin=80, ymax=100,\n    legend entries={},\n]\n"
        + errplot(DROPOUT_COLOR, "DROPOUT")
        + errplot(NOISE_COLOR, "NOISE")
        + "% \\addplot[gray, dashed, line width=0.5pt, forget plot] coordinates {(-0.3,50) (3.3,50)};\n"
        + "\\end{axis}\n\\end{tikzpicture}\n"
    )


def _step_panel(pert: str, color: str, first: bool) -> tuple[str, list[float]]:
    df = _steps("loc", pert.lower())
    df = df[df["bin"].isin(STEP_BINS)]
    rates = sorted(df["rate"].unique())
    xmin, xmax = int(df["step"].min()), int(df["step"].max())
    lines = [
        "\\nextgroupplot[\n    xlabel={\\scriptsize Pretraining step ($\\times 10^3$)},\n"
        + ("    ylabel={\\small Accuracy (\\%)},\n" if first else "")
        + f"    xmin={xmin}, xmax={xmax},\n    scaled x ticks=base 10:-3,\n    xtick scale label code/.code={{}},\n"
        + "    xticklabel style={/pgf/number format/.cd, fixed, precision=0},\n]\n"
    ]
    for rate, shade in zip(rates, SHADES, strict=True):
        c = _shade(color, shade)
        sub = df[df["rate"] == rate].sort_values("step")
        xs = sub["step"].tolist()
        ys = (100 * sub["accuracy_primary"]).tolist()
        se = (100 * sub["accuracy_se_primary"]).tolist()
        lo = [y - e for y, e in zip(ys, se, strict=True)]
        hi = [y + e for y, e in zip(ys, se, strict=True)]
        lines.append(
            f"\\addplot[{c}, fill={c}, fill opacity=0.25, draw=none, forget plot] coordinates {{{_band(xs, lo, hi)}}} --cycle;\n"
        )
        lines.append(
            f"\\addplot[{c}, mark=*, mark size=1, line width=1pt, forget plot] coordinates {{{_coords(xs, ys)}}};\n"
        )
    lines.append(
        f"\\addplot[gray, dashed, line width=0.5pt, forget plot] coordinates {{({xmin},50) ({xmax},50)}};\n"
    )
    return "".join(lines), rates


def steps() -> str:
    left, p_rates = _step_panel("DROPOUT", DROPOUT_COLOR, first=True)
    right, s_rates = _step_panel("NOISE", NOISE_COLOR, first=False)

    def legend(title: str, rates: list[float], color: str) -> str:
        chips = [
            f"\\tikz\\draw[{_shade(color, shade)}, thick, mark=*, mark size=1.5] plot coordinates {{(0,0) (0.4,0)}}; ${r:g}$"
            for r, shade in zip(rates, SHADES, strict=True)
        ]
        return (
            f"{{\\small {title}:\\hspace{{0.5em}}" + "\\hspace{0.8em}".join(chips) + "}"
        )

    return (
        HEADER
        + f"% Panels: pretraining checkpoints at bins {STEP_BINS} of the range (min / mid / max), dropout left, noise right.\n"
        + "\\centering\n"
        + "\\begin{subfigure}{0pt}\\phantomsubcaption\\label{fig:olmo_steps_dropout}\\end{subfigure}%\n"
        + "\\begin{subfigure}{0pt}\\phantomsubcaption\\label{fig:olmo_steps_noise}\\end{subfigure}%\n"
        + legend("dropout $p$", p_rates, DROPOUT_COLOR)
        + "\\hspace{2em}"
        + legend("noise $\\sigma$", s_rates, NOISE_COLOR)
        + "\\\\[3pt]\n"
        + "\\begin{tikzpicture}\n\\begin{groupplot}[\n"
        + "    group style={group size=2 by 1, horizontal sep=0.9cm, yticklabels at=edge left},\n"
        + "    height=5cm,\n    width=0.46\\textwidth,\n    grid=major,\n    ymin=0, ymax=100,\n    legend entries={},\n]\n"
        + left
        + right
        + "\\end{groupplot}\n"
        + "\\node at ([yshift=-1.05cm]group c1r1.south) {\\small (a)};\n"
        + "\\node at ([yshift=-1.05cm]group c2r1.south) {\\small (b)};\n"
        + "\\end{tikzpicture}\n"
    )


def content_clean() -> str:
    df = _steps("ctrl", "clean")
    grp = (
        df.groupby("step")["content_accuracy_primary"]
        .agg(["mean", "std", "count"])
        .sort_index()
    )
    xs = grp.index.tolist()
    ys = (100 * grp["mean"]).tolist()
    se = (100 * grp["std"] / np.sqrt(grp["count"])).fillna(0.0).tolist()
    lo = [y - e for y, e in zip(ys, se, strict=True)]
    hi = [y + e for y, e in zip(ys, se, strict=True)]
    xmin, xmax = int(min(xs)), int(max(xs))
    return (
        HEADER
        + "% Comprehension controls (5 topic pairs, n=1000 each) WITHOUT perturbation, manifest keys step<N>_ctrl_clean.\n"
        + "\\centering\n\\begin{tikzpicture}\n\\begin{axis}[\n    height=5cm,\n    width=0.85\\linewidth,\n    grid=major,\n"
        + "    xlabel={\\small Pretraining step (×10³)},\n    ylabel={\\small Comprehension accuracy (\\%)},\n"
        + f"    xmin={xmin}, xmax={xmax},\n    ymin=0, ymax=100,\n    scaled x ticks=base 10:-3,\n"
        + "    xtick scale label code/.code={},\n    xticklabel style={/pgf/number format/.cd, fixed, precision=0},\n"
        + "    legend entries={},\n]\n"
        + f"\\addplot[{CONTENT_COLOR}, fill={CONTENT_COLOR}, fill opacity=0.25, draw=none, forget plot] coordinates {{{_band(xs, lo, hi)}}} --cycle;\n"
        + f"\\addplot[{CONTENT_COLOR}, mark=*, mark size=1, line width=1pt, forget plot] coordinates {{{_coords(xs, ys)}}};\n"
        + f"\\addplot[gray, dashed, line width=0.5pt, forget plot] coordinates {{({xmin},50) ({xmax},50)}};\n"
        + "\\end{axis}\n\\end{tikzpicture}\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument(
        "--out-dir",
        type=Path,
        default=Path("plots/11_appendix/olmo"),
        help="output directory (default: plots/11_appendix/olmo, as in the paper repo)",
    )
    args = ap.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    for name, render in (
        ("olmo_stages_wrap.tex", stages),
        ("olmo_steps_appendix.tex", steps),
        ("olmo_fig3_content_baseline.tex", content_clean),
    ):
        (args.out_dir / name).write_text(render())
        print(f"wrote {args.out_dir / name}")


if __name__ == "__main__":
    main()
